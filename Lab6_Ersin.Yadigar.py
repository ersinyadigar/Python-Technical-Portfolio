# Lab 6 - String Comparison
# Compare two strings using == and != operators

string1 = input("Enter the first string: ")
string2 = input("Enter the second string: ")

if string1 == string2:
    print("The strings are equal.")
else:
    print("The strings are not equal.")

if string1 != string2:
    print("The != operator confirms that the strings are different.")
else:
    print("The != operator confirms that the strings are equal.")